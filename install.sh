#!/usr/bin/env sh
# One-command install for the Nuck MVP (ADR 0012): generate secrets and the Tuwunel
# config, then start the stack.
set -eu

cd "$(dirname "$0")"

if [ -f .env ]; then
    echo "refusing to overwrite existing .env (delete it to reinstall)" >&2
    exit 1
fi

if ! command -v docker >/dev/null 2>&1; then
    echo "docker is required" >&2
    exit 1
fi

SERVER_NAME="${NUCK_SERVER_NAME:-localhost}"
NUCK_PORT="${NUCK_PORT:-8008}"

# 32 random bytes as hex, without requiring openssl.
secret() {
    head -c 32 /dev/urandom | od -An -tx1 | tr -d ' \n'
}

POSTGRES_PASSWORD="$(secret)"
APPSERVICE_HS_TOKEN="$(secret)"
APPSERVICE_AS_TOKEN="$(secret)"

cat > .env <<EOF
# Generated by install.sh. Never commit this file.
NUCK_SERVER_NAME=$SERVER_NAME
NUCK_PORT=$NUCK_PORT
POSTGRES_PASSWORD=$POSTGRES_PASSWORD
APPSERVICE_HS_TOKEN=$APPSERVICE_HS_TOKEN
APPSERVICE_AS_TOKEN=$APPSERVICE_AS_TOKEN
# Optional: a Tuwunel administrator access token. Only reconciliation (reading room
# state periodically) needs it; the MVP runs without it.
# TUWUNEL_ADMIN_TOKEN=
EOF
chmod 600 .env

mkdir -p data
# Dots in the server name must be escaped inside the AppService namespace regex.
SERVER_RE="$(printf '%s' "$SERVER_NAME" | sed 's/\./\\./g')"
sed \
    -e "s|__SERVER_NAME__|$SERVER_NAME|g" \
    -e "s|__SERVER_RE__|$SERVER_RE|g" \
    -e "s|__HS_TOKEN__|$APPSERVICE_HS_TOKEN|g" \
    -e "s|__AS_TOKEN__|$APPSERVICE_AS_TOKEN|g" \
    deploy/tuwunel.toml.tmpl > data/tuwunel.toml
chmod 600 data/tuwunel.toml

echo "server_name: $SERVER_NAME"
echo "starting the stack (this builds the nuck-server image on first run)…"
docker compose up -d --build

echo
docker compose ps
echo
echo "Waiting for nuck-server…"
i=0
until curl -fsS "http://localhost:$NUCK_PORT/healthz" >/dev/null 2>&1; do
    i=$((i + 1))
    if [ "$i" -ge 60 ]; then
        echo "nuck-server did not become healthy; see: docker compose logs nuck-server" >&2
        exit 1
    fi
    sleep 2
done
curl -fsS "http://localhost:$NUCK_PORT/healthz" && echo
echo
echo "Nuck is up: http://localhost:$NUCK_PORT"
echo "  health:      http://localhost:$NUCK_PORT/healthz"
echo "  server-info: http://localhost:$NUCK_PORT/_nuck/v1/server-info"
